class MockLLMClient(LLMClient):
    """Mock LLMClient for testing DevelopmentAgent with canned responses."""

    def __init__(self, responses: Optional[List[str]] = None) -> None:
        self.responses = list(responses or [])
        self.prompts_received: List[str] = []

    def generate(
        self,
        prompt: str,
        max_tokens: int = 512,
        temperature: float = 0.2,
        stop: list[str] | None = None,
    ) -> str:
        self.prompts_received.append(prompt)
        if self.responses:
            return self.responses.pop(0)
        return "```python\n# Generated by Ojas\n\ndef fallback():\n    return True\n```"

    def stream(
        self,
        prompt: str,
        max_tokens: int = 512,
        temperature: float = 0.2,
        stop: list[str] | None = None,
    ) -> Iterator[str]:
        yield self.generate(prompt, max_tokens, temperature, stop)

    def is_loaded(self) -> bool:
        return True

    def get_info(self) -> dict:
        return {"model_name": "mock-llm", "backend": "mock"}


class MockChunk:
    def __init__(self, req_id: str, heading: str, content: str):
        self.req_id = req_id
        self.heading = heading
        self.content = content


def test_extract_code_block():
    client = MockLLMClient()
    agent = DevelopmentAgent(llm_client=client)

    # Markdown python block
    resp1 = "Here is the code:\n```python\ndef hello():\n    return 'world'\n```\nHope this helps!"
    assert agent._extract_code_block(resp1) == "def hello():\n    return 'world'"

    # Generic block
    resp2 = "```\ndef foo():\n    pass\n```"
    assert agent._extract_code_block(resp2) == "def foo():\n    pass"

    # Plain text without backticks
    resp3 = "def bar():\n    return 42"
    assert agent._extract_code_block(resp3) == "def bar():\n    return 42"


def test_build_context():
    client = MockLLMClient()
    agent = DevelopmentAgent(llm_client=client)

    chunks = [
        MockChunk("REQ-001", "Basic Addition", "The system shall add two integers."),
        MockChunk("REQ-002", "Subtraction", "The system shall subtract two integers."),
    ]
    ctx = agent._build_context(chunks)
    assert "[REQ-001] Basic Addition" in ctx
    assert "The system shall add two integers." in ctx
    assert "[REQ-002] Subtraction" in ctx

    assert "No specific requirement specifications found." in agent._build_context([])


def test_analyze_requirements():
    analysis_json = """
    ```json
    {
      "summary": "Calculator application with arithmetic operations",
      "modules": [
        {"name": "CalculatorCore", "description": "Arithmetic engine", "responsibilities": ["add", "subtract"]}
      ],
      "entities": [
        {"name": "CalculationResult", "fields": ["result", "operation"], "description": "Result container"}
      ],
      "relationships": ["CalculatorCore produces CalculationResult"],
      "constraints": ["Division by zero must raise ValueError"]
    }
    ```
    """
    client = MockLLMClient(responses=[analysis_json])
    agent = DevelopmentAgent(llm_client=client)

    analysis = agent.analyze_requirements("Build a calculator")
    assert isinstance(analysis, RequirementAnalysis)
    assert analysis.summary == "Calculator application with arithmetic operations"
    assert len(analysis.modules) == 1
    assert analysis.modules[0].name == "CalculatorCore"
    assert len(analysis.entities) == 1
    assert "Division by zero must raise ValueError" in analysis.constraints



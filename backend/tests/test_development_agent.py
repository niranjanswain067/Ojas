def test_generate_file_self_correction_retry():
    # Attempt 0: syntax error `def add(a, b:`
    attempt0 = """
```python
# Generated by Ojas
class Calculator:
    def add(a, b:
        return a + b
```
"""
    # Attempt 1: corrected syntax `def add(self, a: int, b: int) -> int:`
    attempt1 = """
```python
# Generated by Ojas
class Calculator:
    def add(self, a: int, b: int) -> int:
        return a + b
```
"""
    client = MockLLMClient(responses=[attempt0, attempt1])
    agent = DevelopmentAgent(llm_client=client)

    file_spec = FileSpec(
        file_path="calculator.py",
        description="Core calculator",
        classes=["Calculator"],
        functions=["add"],
        dependencies=[],
        order=1,
    )

    gen_file = agent.generate_file(file_spec, max_retries=2)
    assert isinstance(gen_file, GeneratedFile)
    assert gen_file.check_result.passed is True
    assert gen_file.retry_count == 1
    # Check that feedback from attempt 0 was sent to LLM on attempt 1
    assert len(client.prompts_received) == 2
    assert "Static analysis failed with the following issues" in client.prompts_received[1]


def test_generate_file_max_retries_exceeded():
    # Both attempts return broken syntax
    bad_code = "```python\ndef broken(:\n    pass\n```"

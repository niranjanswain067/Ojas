def test_delete_file_and_prune_empty_dirs(client, sample_project):
    pid = sample_project["id"]
    # Write nested file
    client.put(f"/api/projects/{pid}/files/deep/nested/folder/target.txt", json={"content": "bye"})

    disk_file = get_workspace_dir(pid) / "deep" / "nested" / "folder" / "target.txt"
    assert disk_file.exists()

    # Delete
    del_resp = client.delete(f"/api/projects/{pid}/files/deep/nested/folder/target.txt")
    assert del_resp.status_code == 204

    # File should be gone
    assert not disk_file.exists()
    # Empty directories should be pruned
    assert not (get_workspace_dir(pid) / "deep").exists()

    # Reading deleted file returns 404
    get_resp = client.get(f"/api/projects/{pid}/files/deep/nested/folder/target.txt")
    assert get_resp.status_code == 404



def test_path_is_safe_valid(sample_project):
    pid = sample_project["id"]
    assert path_is_safe(pid, "hello.py") is True
    assert path_is_safe(pid, "src/components/Button.tsx") is True
    assert path_is_safe(pid, "data/nested/deep/file.json") is True


def test_path_is_safe_blocks_traversal(sample_project):
    pid = sample_project["id"]
    assert path_is_safe(pid, "../outside.py") is False
    assert path_is_safe(pid, "foo/../../outside.py") is False
    assert path_is_safe(pid, "/etc/passwd") is False
    assert path_is_safe(pid, "C:/Windows/System32/calc.exe") is False
    assert path_is_safe(pid, "") is False
    assert path_is_safe(pid, "   ") is False
    assert path_is_safe(pid, "hello.py\0something") is False
    assert path_is_safe(pid, "..") is False
    assert path_is_safe(pid, ".") is False


def test_detect_language():
    assert detect_language(Path("app.py")) == "python"
    assert detect_language(Path("index.ts")) == "typescript"
    assert detect_language(Path("Component.tsx")) == "typescript"

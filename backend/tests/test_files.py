def test_write_and_read_file(client, sample_project):
    pid = sample_project["id"]
    content = "# Generated by Ojas\n\ndef add(a, b):\n    return a + b\n"

    # 1. Write file
    put_resp = client.put(
        f"/api/projects/{pid}/files/calculator.py",
        json={"content": content},
    )
    assert put_resp.status_code == 200
    put_data = put_resp.json()
    assert put_data["path"] == "calculator.py"
    assert put_data["size_bytes"] == len(content.encode("utf-8"))

    # Verify on disk
    disk_path = get_workspace_dir(pid) / "calculator.py"
    assert disk_path.exists()
    assert disk_path.read_text(encoding="utf-8") == content

    # 2. Read file
    get_resp = client.get(f"/api/projects/{pid}/files/calculator.py")
    assert get_resp.status_code == 200
    get_data = get_resp.json()
    assert get_data["path"] == "calculator.py"
    assert get_data["content"] == content
    assert get_data["language"] == "python"
    assert get_data["is_generated"] is True



def test_file_tree_contains_nested_nodes(client, sample_project):
    pid = sample_project["id"]
    client.put(f"/api/projects/{pid}/files/root.txt", json={"content": "root"})
    client.put(f"/api/projects/{pid}/files/pkg/module.py", json={"content": "print(1)"})

    tree_resp = client.get(f"/api/projects/{pid}/files")
    assert tree_resp.status_code == 200
    tree_data = tree_resp.json()

    names = [node["name"] for node in tree_data["tree"]]
    assert "root.txt" in names
    assert "pkg" in names

    # Find the pkg node and check its children
    pkg_node = next(node for node in tree_data["tree"] if node["name"] == "pkg")
    assert pkg_node["type"] == "directory"
    assert any(child["name"] == "module.py" for child in pkg_node["children"])



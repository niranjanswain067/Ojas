    assert detect_language(Path("README.md")) == "markdown"
    assert detect_language(Path("schema.sql")) == "sql"
    assert detect_language(Path("Dockerfile")) == "dockerfile"
    assert detect_language(Path("notes.unknownext")) == "plaintext"



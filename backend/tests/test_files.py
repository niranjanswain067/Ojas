def test_path_traversal_attacks_blocked(client, sample_project):
    pid = sample_project["id"]

    # Traversal using URL-encoded slashes so the HTTP client does not normalize client-side
    resp = client.get(f"/api/projects/{pid}/files/..%2F..%2Fetc%2Fpasswd")
    assert resp.status_code == 400
    assert "traversal" in resp.json()["detail"].lower() or "unsafe" in resp.json()["detail"].lower()

    # Traversal in write
    resp = client.put(f"/api/projects/{pid}/files/..%2Fmalicious.txt", json={"content": "bad"})
    assert resp.status_code == 400

    # Backslash traversal
    resp = client.put(f"/api/projects/{pid}/files/..%5Cmalicious.txt", json={"content": "bad"})
    assert resp.status_code == 400

    # Traversal in delete
    resp = client.delete(f"/api/projects/{pid}/files/..%2F..%2Fmalicious.txt")
    assert resp.status_code == 400

def setup_module():
    init_database()


class MockLLM(LLMClient):
    """Mock LLM producing canned responses for orchestrator testing."""

    def __init__(self, responses: Optional[List[str]] = None) -> None:
        self.responses = list(responses or [])

    def generate(
        self,
        prompt: str,
        max_tokens: int = 512,
        temperature: float = 0.2,
        stop: list[str] | None = None,
    ) -> str:
        if self.responses:
            return self.responses.pop(0)
        return """
```python
# Generated by Ojas

def add(a: int, b: int) -> int:
    return a + b
```
"""

    def stream(
        self,
        prompt: str,
        max_tokens: int = 512,
        temperature: float = 0.2,
        stop: list[str] | None = None,
    ) -> Iterator[str]:
        yield self.generate(prompt, max_tokens, temperature, stop)

    def is_loaded(self) -> bool:
        return True

    def get_info(self) -> dict:
        return {"model_name": "mock"}


def test_orchestrator_run_plan():
    analysis_json = json.dumps({
        "summary": "Calculator service",
        "modules": [{"name": "Core", "description": "Math", "responsibilities": ["Add"]}],
        "entities": [],
        "relationships": [],
        "constraints": [],
    })
    plan_json = json.dumps({
        "project_name": "Calc",
        "plan_summary": "Math plan",
        "files": [
            {
                "file_path": "calc.py",
                "description": "Math functions",
                "classes": [],
                "functions": ["add"],
                "dependencies": [],
                "order": 1,
            }
        ],
    })

    mock_llm = MockLLM(responses=[analysis_json, plan_json])
    event_bus = EventBus()
    task_mgr = TaskManager()

    orchestrator = Orchestrator(
        llm_client=mock_llm,
        task_manager=task_mgr,
        event_bus=event_bus,
    )

    project_id = str(uuid.uuid4())
    res = orchestrator.run_plan(project_id, prompt="Build calculator")

    assert isinstance(res, RunResult)
    assert res.success is True
    assert res.status == "pending_approval"
    assert res.plan_text is not None
    assert "calc.py" in res.plan_text



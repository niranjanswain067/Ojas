def test_orchestrator_cancellation():
    plan_dict = {
        "project_name": "CancelProject",
        "plan_summary": "Summary",
        "files": [
            {"file_path": "file1.py", "description": "f1", "classes": [], "functions": [], "dependencies": [], "order": 1},
            {"file_path": "file2.py", "description": "f2", "classes": [], "functions": [], "dependencies": [], "order": 2},
        ],
    }

    mock_llm = MockLLM()
    event_bus = EventBus()
    task_mgr = TaskManager()

    orchestrator = Orchestrator(
        llm_client=mock_llm,
        task_manager=task_mgr,
        event_bus=event_bus,
    )

    project_id = str(uuid.uuid4())
    run_id = str(uuid.uuid4())

    # Pre-register and trigger cancellation
    task_mgr._cancel_events[run_id] = task_mgr._cancel_events.get(run_id) or TaskManager()._lock.__class__()
    import threading
    ev = threading.Event()
    ev.set()
    task_mgr._cancel_events[run_id] = ev

    res = orchestrator.run_develop(
        project_id=project_id,
        prompt="Build with cancel",
        plan_text=json.dumps(plan_dict),
        run_id=run_id,
    )

    assert res.success is False
    assert res.status == "cancelled"
    assert res.stop_reason == "user_cancelled"

"""
Unit tests for backend.app.validation.static_check
"""

import tempfile
from pathlib import Path

from backend.app.schemas.development import CheckIssue, CheckResult
from backend.app.validation.static_check import check_file, check_lint, check_syntax


def test_check_syntax_valid():
    code = """
def add(a: int, b: int) -> int:
    \"\"\"Add two numbers.\"\"\"
    return a + b
"""
    result = check_syntax(code)
    assert result.passed is True
    assert len(result.issues) == 0


def test_check_syntax_invalid():
    code = "def invalid_func(:"
    result = check_syntax(code)
    assert result.passed is False
    assert len(result.issues) == 1
    assert result.issues[0].code == "E999"
    assert result.issues[0].line == 1
    assert "syntax" in result.issues[0].message.lower() or "invalid" in result.issues[0].message.lower()


def test_check_syntax_indentation_error():
    code = "def foo():\nx = 1"
    result = check_syntax(code)
    assert result.passed is False
    assert len(result.issues) == 1
    assert result.issues[0].code == "E998"


def test_check_file_syntax_failure_skips_lint(monkeypatch):
    called_lint = False

    def mock_check_lint(path):
        nonlocal called_lint
        called_lint = True
        return CheckResult(passed=True, issues=[])

    monkeypatch.setattr("backend.app.validation.static_check.check_lint", mock_check_lint)

    code = "def bad_syntax(:"
    res = check_file(code)
    assert res.passed is False
    assert called_lint is False


def test_check_file_valid_python():
    code = """
# Generated by Ojas

def multiply(x: float, y: float) -> float:
    return x * y
"""
    res = check_file(code)
    assert res.passed is True
    assert len(res.issues) == 0


def test_check_lint_nonexistent_file():
    res = check_lint("non_existent_file_path_12345.py")
    assert res.passed is True
    assert len(res.issues) == 0


def test_check_result_to_prompt_message():
    result = CheckResult(
        passed=False,
        issues=[
            CheckIssue(line=10, col=4, code="E999", message="invalid syntax"),
            CheckIssue(line=15, col=1, code="F401", message="unused import"),
        ],
    )
    prompt_msg = result.to_prompt_message()
    assert "Line 10, Col 4 [E999]: invalid syntax" in prompt_msg
    assert "Line 15, Col 1 [F401]: unused import" in prompt_msg
    assert "Please fix all listed syntax/lint errors" in prompt_msg


def test_check_result_to_prompt_message_empty():
    result = CheckResult(passed=True, issues=[])
    assert result.to_prompt_message() == ""

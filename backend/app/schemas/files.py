"""
Pydantic schemas for Workspace File Management API.
Defined per 06_API_Specification.md and 09_Implementation_Plan.md (Phase 9).
"""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class FileNode(BaseModel):
    """Represents a file or directory node in the workspace file tree."""
    name: str = Field(..., description="File or folder name")
    path: str = Field(..., description="Relative path from workspace root, forward slashes")
    type: Literal["file", "directory"] = Field(..., description="Node type")
    size_bytes: int = Field(default=0, description="File size in bytes (0 for directories)")
    is_generated: bool = Field(default=False, description="Whether generated by Ojas")
    pending_approval: bool = Field(default=False, description="Whether diff needs approval")
    updated_at: Optional[str] = Field(default=None, description="ISO timestamp of last modification")
    children: Optional[List["FileNode"]] = Field(
        default=None,
        description="Children nodes if this is a directory"
    )


# Enable recursive self-referential Pydantic model
FileNode.model_rebuild()


class FileTreeResponse(BaseModel):
    """File tree response containing root list of nodes."""
    tree: List[FileNode] = Field(default_factory=list, description="Top-level nodes in workspace")
    root: Optional[FileNode] = Field(default=None, description="Optional root node representation")


class FileContentResponse(BaseModel):
    """Content and metadata for a single workspace file."""
    path: str = Field(..., description="Relative file path")
    content: str = Field(..., description="Full text content of the file")
    size_bytes: int = Field(..., description="Size in bytes")
    language: str = Field(..., description="Detected programming/markup language")
    is_generated: bool = Field(default=False, description="Whether generated by Ojas")
    pending_approval: bool = Field(default=False, description="Whether diff needs approval")
    linked_req_ids: List[str] = Field(default_factory=list, description="Associated requirement IDs")
    updated_at: Optional[str] = Field(default=None, description="ISO timestamp of last modification")


class FileSaveRequest(BaseModel):
    """Request payload to write or overwrite a file."""
    content: str = Field(default="", description="Content to write into the file")


class FileSaveResponse(BaseModel):
    """Response returned upon saving a file."""
    path: str = Field(..., description="Relative file path")
    size_bytes: int = Field(..., description="Written size in bytes")
    updated_at: str = Field(..., description="ISO timestamp of last modification")

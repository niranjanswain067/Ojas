"""
Pydantic schemas and data transfer models for Development Agent and Static Checker.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class CheckIssue(BaseModel):
    """An individual syntax or lint issue detected in source code."""

    line: int = Field(default=1, description="Line number of the issue")
    col: int = Field(default=1, description="Column number of the issue")
    code: str = Field(default="SYNTAX", description="Rule or error code (e.g. SYNTAX, F401, E999)")
    message: str = Field(description="Descriptive error or warning message")


class CheckResult(BaseModel):
    """Result returned by static analysis checks (AST syntax + ruff)."""

    passed: bool = Field(description="True if the code passed all checks without blocking errors")
    issues: List[CheckIssue] = Field(default_factory=list, description="List of detected issues")

    def to_prompt_message(self) -> str:
        """Format detected issues into a concise instruction block for model self-correction."""
        if not self.issues:
            return ""
        lines = ["Static analysis failed with the following issues:"]
        for issue in self.issues:
            lines.append(f"- Line {issue.line}, Col {issue.col} [{issue.code}]: {issue.message}")
        lines.append("Please fix all listed syntax/lint errors and return the corrected Python code.")
        return "\n".join(lines)


class ModuleSpec(BaseModel):
    """Specification of a software module identified during requirement analysis."""

    name: str = Field(description="Module or subsystem name")
    description: str = Field(default="", description="Summary of module purpose")
    responsibilities: List[str] = Field(default_factory=list, description="List of responsibilities")


class EntitySpec(BaseModel):
    """Specification of a domain entity or class identified in requirements."""

    name: str = Field(description="Entity or class name")
    fields: List[str] = Field(default_factory=list, description="Core attributes or data fields")
    description: str = Field(default="", description="Description of the entity")


class RequirementAnalysis(BaseModel):
    """Structured architectural analysis derived from user prompt and requirements."""

    summary: str = Field(description="High-level architecture and scope summary")
    modules: List[ModuleSpec] = Field(default_factory=list, description="Identified functional modules")
    entities: List[EntitySpec] = Field(default_factory=list, description="Identified data models and entities")
    relationships: List[str] = Field(default_factory=list, description="Relationships between entities")
    constraints: List[str] = Field(default_factory=list, description="Technical or domain constraints")


class FileSpec(BaseModel):
    """Specification for an individual source code file in the development plan."""

    file_path: str = Field(description="Relative file path (e.g., calculator.py, models/book.py)")
    description: str = Field(description="Purpose of the file and functionality it implements")
    classes: List[str] = Field(default_factory=list, description="Classes to define in this file")
    functions: List[str] = Field(default_factory=list, description="Top-level functions to define")
    dependencies: List[str] = Field(default_factory=list, description="Files or packages this file depends on")
    order: int = Field(default=1, description="Sequential generation order")


class DevelopmentPlan(BaseModel):
    """Ordered development plan mapping requirements to concrete files."""

    project_name: str = Field(default="OjasProject", description="Project name")
    plan_summary: str = Field(description="High-level implementation strategy")
    files: List[FileSpec] = Field(default_factory=list, description="Ordered list of files to generate")


class GeneratedFile(BaseModel):
    """A source file generated by the Development Agent with verification results."""

    file_path: str = Field(description="Target workspace file path")
    content: str = Field(description="Generated Python source code")
    is_generated: bool = Field(default=True, description="True if generated by Ojas")
    check_result: CheckResult = Field(description="Static verification outcome")
    retry_count: int = Field(default=0, description="Number of self-correction attempts made (max 2)")


class BugReport(BaseModel):
    """A structured bug report detailing a test failure or code deficiency."""

    bug_id: str = Field(description="Unique bug identifier (e.g. B-001)")
    req_id: Optional[str] = Field(default=None, description="Linked requirement identifier (e.g. REQ-001)")
    tc_id: Optional[str] = Field(default=None, description="Linked test case identifier (e.g. TC-001)")
    file_path: str = Field(description="Target file path containing the bug")
    function_name: str = Field(description="Function or method name requiring correction")
    expected_result: str = Field(description="Expected behavior according to requirements")
    actual_result: str = Field(description="Actual failure message or trace")
    probable_cause: str = Field(default="", description="Root cause diagnosis")
    severity: str = Field(default="medium", description="Severity level: low, medium, high, critical")

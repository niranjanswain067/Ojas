# Directories and files to exclude from the workspace tree
EXCLUDED_NAMES: Set[str] = {
    ".git",
    "__pycache__",
    ".pytest_cache",
    ".ruff_cache",
    ".mypy_cache",
    ".DS_Store",
    "Thumbs.db",
    ".venv",
    "venv",
    "node_modules",
}

GENERATED_MARKERS: Tuple[str, ...] = (
    "# Generated by Ojas",
    "// Generated by Ojas",
    "/* Generated by Ojas",
    "<!-- Generated by Ojas",
    "Generated by Ojas",
)


def detect_language(file_path: Path) -> str:
    """Detect Monaco-compatible language identifier from file extension or name."""
    name_lower = file_path.name.lower()
    if name_lower == "dockerfile":
        return "dockerfile"
    if name_lower == "makefile":
        return "makefile"
    if name_lower in ("package.json", "tsconfig.json"):
        return "json"

    ext = file_path.suffix.lower()
    return LANGUAGE_MAPPINGS.get(ext, "plaintext")


def check_is_generated(content: str) -> bool:
    """Check if content has the Ojas generation header or marker."""
    header = content[:1000]
    return any(marker in header for marker in GENERATED_MARKERS)


def path_is_safe(project_id: str, file_path: str) -> bool:
    """
    Validate that file_path does not escape workspace/<project_id>/.
    Rejects:
      - Null bytes
      - Absolute paths (both POSIX '/' and Windows drive letters 'C:')
      - '..' directory traversal segments
      - Paths that resolve outside the workspace root
    """
    if not file_path or "\0" in file_path:
        return False

    raw = file_path.strip()
    if not raw:
        return False

    # Check for drive letter or absolute path syntax
    if ":" in raw or raw.startswith("/") or raw.startswith("\\"):
        return False

    # Normalize slashes and split
    normalized = raw.replace("\\", "/")
    segments = [s for s in normalized.split("/") if s]
    if not segments:
        return False

    # Prohibit '..' or '.' segments
    if any(s in ("..", ".") for s in segments):
        return False

    # Resolve against the workspace root
    ws_dir = get_workspace_dir(project_id).resolve()
    try:
        target = (ws_dir / "/".join(segments)).resolve()
        # Ensure target is strictly inside workspace
        return ws_dir in target.parents and target != ws_dir
    except Exception:
        return False


def resolve_safe_path(project_id: str, file_path: str) -> Path:
    """
    Resolve file_path relative to workspace/<project_id>/ and enforce safety.

    Raises:
        ValueError: If path traversal or unsafe path is detected.
        KeyError: If project does not exist.
    """
    # Ensure project exists
    project = get_project(project_id)
    if not project:
        raise KeyError(f"Project '{project_id}' not found.")

    if not path_is_safe(project_id, file_path):
        raise ValueError(f"Unsafe path or path traversal detected: '{file_path}'")

    ws_dir = get_workspace_dir(project_id).resolve()
    clean_path = file_path.replace("\\", "/").strip().lstrip("/")
    return (ws_dir / clean_path).resolve()


def _format_mtime(timestamp: float) -> str:
    """Format Unix timestamp as ISO 8601 string."""
    return datetime.fromtimestamp(timestamp, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%S")


def _build_node(path: Path, ws_dir: Path) -> Optional[FileNode]:
    """Recursively build a FileNode for a file or directory."""
    name = path.name
    if name in EXCLUDED_NAMES:
        return None

    try:
        stat = path.stat()
    except OSError:
        return None

    rel_path = path.relative_to(ws_dir).as_posix()
    updated_at = _format_mtime(stat.st_mtime)

    if path.is_dir():
        children: List[FileNode] = []
        try:
            entries = sorted(
                path.iterdir(),
                key=lambda p: (not p.is_dir(), p.name.lower())
            )
            for entry in entries:
                child_node = _build_node(entry, ws_dir)
                if child_node is not None:
                    children.append(child_node)
        except PermissionError:
            pass

        return FileNode(
            name=name,
            path=rel_path,
            type="directory",
            size_bytes=0,
            is_generated=False,
            pending_approval=False,
            updated_at=updated_at,
            children=children,
        )
    else:
        # Check generated status for text files
        is_generated = False
        try:
            if stat.st_size < 1_000_000:  # Only read first part if < 1MB
                with path.open("r", encoding="utf-8", errors="ignore") as f:
                    chunk = f.read(1000)
                    is_generated = any(marker in chunk for marker in GENERATED_MARKERS)
        except Exception:
            pass

        return FileNode(
            name=name,
            path=rel_path,
            type="file",
            size_bytes=stat.st_size,
            is_generated=is_generated,
            pending_approval=False,
            updated_at=updated_at,
            children=None,
        )


def get_file_tree(project_id: str) -> FileTreeResponse:
    """
    Walk workspace/<project_id>/ recursively and return the file tree.

    Raises:
        KeyError: If project does not exist.
    """
    project = get_project(project_id)
    if not project:
        raise KeyError(f"Project '{project_id}' not found.")

    ws_dir = get_workspace_dir(project_id).resolve()
    ws_dir.mkdir(parents=True, exist_ok=True)

    tree: List[FileNode] = []
    try:
        entries = sorted(
            ws_dir.iterdir(),
            key=lambda p: (not p.is_dir(), p.name.lower())
        )
        for entry in entries:
            node = _build_node(entry, ws_dir)
            if node is not None:
                tree.append(node)
    except PermissionError:
        pass

    root_node = FileNode(
        name=project["name"],
        path="",
        type="directory",
        size_bytes=0,
        is_generated=False,
        pending_approval=False,
        updated_at=project.get("updated_at"),
        children=tree,
    )

    return FileTreeResponse(tree=tree, root=root_node)


def read_file(project_id: str, file_path: str) -> FileContentResponse:
    """
    Read content and metadata of a file within the project workspace.

    Raises:
        KeyError: If project does not exist.
        ValueError: If file_path is unsafe.
        FileNotFoundError: If the file does not exist.
        IsADirectoryError: If file_path refers to a directory.
    """
    target = resolve_safe_path(project_id, file_path)

    if not target.exists():
        raise FileNotFoundError(f"File '{file_path}' does not exist in project '{project_id}'.")

    if target.is_dir():
        raise IsADirectoryError(f"Path '{file_path}' is a directory, not a file.")

    stat = target.stat()
    content = target.read_text(encoding="utf-8", errors="replace")
    ws_dir = get_workspace_dir(project_id).resolve()
    rel_path = target.relative_to(ws_dir).as_posix()

    return FileContentResponse(
        path=rel_path,
        content=content,
        size_bytes=stat.st_size,
        language=detect_language(target),
        is_generated=check_is_generated(content),
        pending_approval=False,
        linked_req_ids=[],
        updated_at=_format_mtime(stat.st_mtime),
    )


def write_file(project_id: str, file_path: str, content: str) -> FileSaveResponse:
    """
    Write or overwrite a file within the project workspace, creating parent dirs if needed.

    Raises:
        KeyError: If project does not exist.
        ValueError: If file_path is unsafe.
        IsADirectoryError: If file_path already exists as a directory.
    """
    target = resolve_safe_path(project_id, file_path)

    if target.exists() and target.is_dir():
        raise IsADirectoryError(f"Cannot overwrite directory '{file_path}' with file content.")

    # Create parent directories
    target.parent.mkdir(parents=True, exist_ok=True)

    # Write content to disk verbatim without newline translation
    target.write_text(content, encoding="utf-8", newline="")
    stat = target.stat()
    ws_dir = get_workspace_dir(project_id).resolve()
    rel_path = target.relative_to(ws_dir).as_posix()

    return FileSaveResponse(
        path=rel_path,
        size_bytes=stat.st_size,
        updated_at=_format_mtime(stat.st_mtime),
    )


def delete_file(project_id: str, file_path: str) -> bool:
    """
    Delete a file from the project workspace and prune any empty parent folders.

    Raises:
        KeyError: If project does not exist.
        ValueError: If file_path is unsafe or attempts to delete workspace root.
        FileNotFoundError: If the file does not exist.
    """
    target = resolve_safe_path(project_id, file_path)
    ws_dir = get_workspace_dir(project_id).resolve()

    if not target.exists():
        raise FileNotFoundError(f"File '{file_path}' does not exist in project '{project_id}'.")

    if target == ws_dir:
        raise ValueError("Cannot delete the workspace root directory.")

    if target.is_dir():
        shutil.rmtree(target)
    else:
        target.unlink()
        # Clean up empty parent directories up to workspace root
        parent = target.parent
        while parent != ws_dir and parent.exists():
            try:
                # If directory is completely empty, prune it
                if not any(parent.iterdir()):
                    parent.rmdir()
                    parent = parent.parent
                else:
                    break
            except OSError:
                break

    return True
